// Command gen generates package api from the Herdr API JSON Schema
// (`herdr api schema --json`). It emits:
//
//   - a Go type for every schema definition (structs, string enums, unions);
//   - a typed function per request method, e.g.
//     func (c Client) PaneLayout(ctx, p PaneLayoutParams) (PaneLayoutResponse, error);
//   - the event envelope union and event-kind constants.
//
// Tagged unions (oneOf whose variants share a const discriminator property)
// become a wrapper struct holding a sealed interface value. Unknown variants
// decode into <Union>Unknown so a newer server does not break older clients.
// Untagged unions stay json.RawMessage.
//
// The schema does not say which response a method returns, so that mapping
// lives in responses.go and is checked at decode time: every response variant
// verifies its "type" discriminator.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"unicode"
)

// Schema is the subset of JSON Schema that the Herdr schema uses.
type Schema struct {
	Any         bool               `json:"-"` // `true` schema
	Ref         string             `json:"$ref"`
	Type        json.RawMessage    `json:"type"`
	Properties  map[string]*Schema `json:"properties"`
	Required    []string           `json:"required"`
	Enum        []string           `json:"enum"`
	Const       *string            `json:"const"`
	OneOf       []*Schema          `json:"oneOf"`
	AnyOf       []*Schema          `json:"anyOf"`
	Items       *Schema            `json:"items"`
	AddlProps   json.RawMessage    `json:"additionalProperties"`
	Format      string             `json:"format"`
	Default     any                `json:"default"`
	Description string             `json:"description"`
	Title       string             `json:"title"`
	Defs        map[string]*Schema `json:"$defs"`
}

func (s *Schema) UnmarshalJSON(b []byte) error {
	t := bytes.TrimSpace(b)
	if string(t) == "true" || string(t) == "false" {
		s.Any = true
		return nil
	}
	type alias Schema
	return json.Unmarshal(b, (*alias)(s))
}

func (s *Schema) types() []string {
	if s == nil || len(s.Type) == 0 {
		return nil
	}
	var one string
	if json.Unmarshal(s.Type, &one) == nil {
		return []string{one}
	}
	var many []string
	_ = json.Unmarshal(s.Type, &many)
	return many
}

// baseType returns the non-null type and whether null is allowed.
func (s *Schema) baseType() (string, bool) {
	var base string
	null := false
	for _, t := range s.types() {
		if t == "null" {
			null = true
		} else {
			base = t
		}
	}
	return base, null
}

func (s *Schema) isRequired(name string) bool {
	for _, r := range s.Required {
		if r == name {
			return true
		}
	}
	return false
}

func (s *Schema) addl() (*Schema, bool) {
	if len(s.AddlProps) == 0 {
		return nil, false
	}
	var sub Schema
	if err := json.Unmarshal(s.AddlProps, &sub); err != nil {
		return nil, false
	}
	return &sub, true
}

type Root struct {
	Protocol      int                `json:"protocol"`
	SchemaVersion int                `json:"schema_version"`
	Schemas       map[string]*Schema `json:"schemas"`
}

// ---- generator ------------------------------------------------------------

type kind int

const (
	kStruct kind = iota
	kUnion
	kEnum
	kAlias
)

type gen struct {
	defs  map[string]*Schema
	kinds map[string]kind
	out   bytes.Buffer
	done  map[string]bool
	queue []pending
	names map[string]string // every emitted top-level identifier -> origin
}

type pending struct {
	name string
	s    *Schema
	// for union variants
	unionName, disc, discVal string
}

func main() {
	in := flag.String("schema", "../schema/herdr-api.schema.json", "schema path")
	out := flag.String("out", "zz_generated.go", "output path")
	flag.Parse()

	b, err := os.ReadFile(*in)
	check(err)
	var root Root
	check(json.Unmarshal(b, &root))

	g := &gen{defs: map[string]*Schema{}, kinds: map[string]kind{}, done: map[string]bool{}, names: map[string]string{}}
	for _, sch := range sortedKeys(root.Schemas) {
		for name, d := range root.Schemas[sch].Defs {
			if prev, ok := g.defs[name]; ok {
				pb, _ := json.Marshal(prev)
				db, _ := json.Marshal(d)
				if !bytes.Equal(normRefs(pb), normRefs(db)) {
					fail("definition %s differs between schemas", name)
				}
				continue
			}
			g.defs[name] = d
		}
	}
	for name, d := range g.defs {
		g.kinds[name] = g.classify(d)
	}

	g.p("// Code generated by herdr-gen from the Herdr API schema (protocol %d, schema version %d). DO NOT EDIT.\n\n", root.Protocol, root.SchemaVersion)
	g.p("package api\n\nimport (\n\"context\"\n\"encoding/json\"\n\"fmt\"\n)\n\n")
	g.p("// Protocol is the Herdr socket protocol version this package was generated from.\nconst Protocol = %d\n\n", root.Protocol)
	g.p("var _ = fmt.Errorf\n\n")

	for _, name := range sortedKeys(g.defs) {
		g.emitDef(name, g.defs[name])
	}
	g.emitResponses(root.Schemas["success_response"])
	g.emitMethods(root.Schemas["request"])
	g.emitEnvelope(root.Schemas["event"], root.Schemas["subscription_event"])
	g.drain()

	src, err := format.Source(g.out.Bytes())
	if err != nil {
		_ = os.WriteFile(*out, g.out.Bytes(), 0o644)
		fail("gofmt: %v (unformatted output written to %s)", err, *out)
	}
	check(os.WriteFile(*out, src, 0o644))
}

func normRefs(b []byte) []byte {
	s := string(b)
	for _, sch := range []string{"request", "success_response", "event", "subscription_event", "error_response"} {
		s = strings.ReplaceAll(s, "#/schemas/"+sch+"/$defs/", "#/$defs/")
	}
	return []byte(s)
}

func (g *gen) p(f string, a ...any) { fmt.Fprintf(&g.out, f, a...) }

func (g *gen) claim(name, origin string) {
	if prev, ok := g.names[name]; ok {
		fail("identifier %s generated twice (%s and %s)", name, prev, origin)
	}
	g.names[name] = origin
}

func (g *gen) resolve(s *Schema) *Schema {
	for s != nil && s.Ref != "" {
		s = g.defs[refName(s.Ref)]
	}
	return s
}

func refName(ref string) string { return ref[strings.LastIndex(ref, "/")+1:] }

func (g *gen) classify(s *Schema) kind {
	if len(s.Enum) > 0 {
		return kEnum
	}
	if _, ok := g.discriminator(s); ok {
		return kUnion
	}
	if base, _ := s.baseType(); base == "object" && len(s.OneOf) == 0 && len(s.AnyOf) == 0 {
		if _, isMap := s.addl(); !isMap || len(s.Properties) > 0 {
			return kStruct
		}
	}
	return kAlias
}

// discriminator finds the property that holds a const in every variant.
func (g *gen) discriminator(s *Schema) (string, bool) {
	vs := s.OneOf
	if len(vs) == 0 {
		vs = s.AnyOf
	}
	if len(vs) < 2 {
		return "", false
	}
	var cands []string
	first := g.resolve(vs[0])
	if first == nil {
		return "", false
	}
	for name, p := range first.Properties {
		if p.Const != nil {
			cands = append(cands, name)
		}
	}
	sort.Strings(cands)
	for _, c := range cands {
		ok := true
		for _, v := range vs {
			rv := g.resolve(v)
			if rv == nil || rv.Properties[c] == nil || rv.Properties[c].Const == nil {
				ok = false
				break
			}
		}
		if ok {
			return c, true
		}
	}
	return "", false
}

// ---- types ----------------------------------------------------------------

// goType returns the Go type for s. ctx names inline types that need one.
func (g *gen) goType(s *Schema, ctx string) string {
	if s == nil || s.Any {
		return "json.RawMessage"
	}
	if s.Ref != "" {
		return refName(s.Ref)
	}
	if nonNull, ok := nullableOf(s); ok {
		return g.goType(nonNull, ctx)
	}
	if len(s.Enum) > 0 {
		g.enqueue(ctx, s)
		return ctx
	}
	if len(s.OneOf) > 0 || len(s.AnyOf) > 0 {
		if _, ok := g.discriminator(s); ok {
			g.enqueue(ctx, s)
			return ctx
		}
		return "json.RawMessage"
	}
	base, _ := s.baseType()
	switch base {
	case "string":
		return "string"
	case "boolean":
		return "bool"
	case "number":
		return "float64"
	case "integer":
		switch s.Format {
		case "uint64":
			return "uint64"
		case "int64":
			return "int64"
		}
		return "int"
	case "array":
		return "[]" + g.goType(s.Items, ctx+"Item")
	case "object":
		if len(s.Properties) > 0 {
			g.enqueue(ctx, s)
			return ctx
		}
		if sub, ok := s.addl(); ok {
			return "map[string]" + g.goType(sub, ctx+"Value")
		}
		return "json.RawMessage"
	}
	return "json.RawMessage"
}

// nullableOf unwraps anyOf/oneOf [X, null].
func nullableOf(s *Schema) (*Schema, bool) {
	vs := s.AnyOf
	if len(vs) == 0 {
		vs = s.OneOf
	}
	if len(vs) != 2 {
		return nil, false
	}
	for i, v := range vs {
		if t := v.types(); len(t) == 1 && t[0] == "null" {
			return vs[1-i], true
		}
	}
	return nil, false
}

func (g *gen) isNullable(s *Schema) bool {
	if s == nil {
		return false
	}
	if _, ok := nullableOf(s); ok {
		return true
	}
	_, null := s.baseType()
	return null
}

func (g *gen) enqueue(name string, s *Schema) {
	if g.done[name] {
		return
	}
	g.done[name] = true
	g.kinds[name] = g.classify(s)
	g.queue = append(g.queue, pending{name: name, s: s})
}

func (g *gen) drain() {
	for len(g.queue) > 0 {
		q := g.queue[0]
		g.queue = g.queue[1:]
		if q.unionName != "" {
			g.emitVariant(q)
		} else {
			g.emitType(q.name, q.s)
		}
	}
}

func (g *gen) emitDef(name string, s *Schema) {
	if g.done[name] {
		return
	}
	g.done[name] = true
	g.emitType(name, s)
	g.drain()
}

func (g *gen) emitType(name string, s *Schema) {
	g.claim(name, "type")
	g.doc(name, s.Description)
	switch g.classify(s) {
	case kEnum:
		g.p("type %s string\n\n", name)
		g.p("const (\n")
		for _, v := range s.Enum {
			c := name + pascal(v)
			g.claim(c, "enum "+name)
			g.p("%s %s = %q\n", c, name, v)
		}
		g.p(")\n\n")
	case kStruct:
		g.p("type %s struct {\n", name)
		g.fields(name, s, "")
		g.p("}\n\n")
	case kUnion:
		pattern := "%[1]s%[2]s"
		if p, ok := variantNames[name]; ok {
			pattern = p
		}
		g.emitUnion(name, s, pattern)
	default:
		g.p("type %s = %s\n\n", name, g.goType(s, name+"Value"))
	}
}

func (g *gen) fields(owner string, s *Schema, skip string) {
	for _, prop := range sortedKeys(s.Properties) {
		if prop == skip {
			continue
		}
		ps := s.Properties[prop]
		req := s.isRequired(prop)
		t := g.goType(ps, owner+pascal(prop))
		rs := g.resolve(ps)
		if nn, ok := nullableOf(ps); ok {
			rs = g.resolve(nn)
		}
		if k, named := g.kinds[t]; named && (k == kStruct || k == kUnion) && (!req || g.isNullable(ps)) {
			t = "*" + t
		} else if t == "bool" && !req && ps.Default == true {
			t = "*bool" // omitted means true; nil keeps the default
		}
		_ = rs
		tag := prop
		if !req {
			tag += ",omitempty"
		}
		desc := ps.Description
		if ps.Default != nil && ps.Default != false && ps.Default != "" {
			if desc != "" {
				desc += " "
			}
			desc += fmt.Sprintf("Default: %v.", ps.Default)
		}
		if desc != "" {
			for _, l := range wrap(desc, 76) {
				g.p("// %s\n", l)
			}
		}
		g.p("%s %s `json:%q`\n", pascal(prop), t, tag)
	}
}

// emitUnion emits a tagged union. pattern formats variant names from
// (union name, pascal(discriminator value)).
func (g *gen) emitUnion(name string, s *Schema, pattern string) {
	disc, _ := g.discriminator(s)
	vs := s.OneOf
	if len(vs) == 0 {
		vs = s.AnyOf
	}
	iface := name + "Variant"
	unknown := name + "Unknown"
	g.claim(iface, "union "+name)
	g.claim(unknown, "union "+name)
	g.p("type %s struct {\n// Value holds one of the %s implementations.\nValue %s\n}\n\n", name, iface, iface)
	g.p("// %s is implemented by every variant of %s.\ntype %s interface{ is%s() }\n\n", iface, name, iface, name)
	g.p("// %s holds a %s variant this package does not know.\ntype %s struct {\n%s string\nRaw json.RawMessage\n}\n\n", unknown, name, unknown, pascal(disc))
	g.p("func (%s) is%s() {}\n\n", unknown, name)
	g.p("func (u %s) MarshalJSON() ([]byte, error) { return u.Raw, nil }\n\n", unknown)
	g.p("func (u %s) MarshalJSON() ([]byte, error) {\nif u.Value == nil { return []byte(\"null\"), nil }\nreturn json.Marshal(u.Value)\n}\n\n", name)
	g.p("func (u *%s) UnmarshalJSON(b []byte) error {\n", name)
	g.p("var probe struct{ D string `json:%q` }\nif err := json.Unmarshal(b, &probe); err != nil { return err }\nswitch probe.D {\n", disc)
	for _, v := range vs {
		rv := g.resolve(v)
		val := *rv.Properties[disc].Const
		vname := fmt.Sprintf(pattern, name, pascal(val))
		if v.Ref != "" {
			vname = refName(v.Ref)
		}
		g.p("case %q:\nvar v %s\nif err := json.Unmarshal(b, &v); err != nil { return err }\nu.Value = v\n", val, vname)
		if v.Ref != "" {
			g.done[vname] = true // emitted as a variant, not a plain def
		}
		g.kinds[vname] = kStruct
		g.queue = append(g.queue, pending{name: vname, s: rv, unionName: name, disc: disc, discVal: val})
	}
	g.p("default:\nu.Value = %s{%s: probe.D, Raw: append(json.RawMessage(nil), b...)}\n}\nreturn nil\n}\n\n", unknown, pascal(disc))
}

func (g *gen) emitVariant(q pending) {
	g.claim(q.name, "variant of "+q.unionName)
	g.doc(q.name, q.s.Description)
	g.p("type %s struct {\n", q.name)
	g.fields(q.name, q.s, q.disc)
	g.p("}\n\n")
	g.p("func (%s) is%s() {}\n\n", q.name, q.unionName)
	g.p(`func (v %[1]s) MarshalJSON() ([]byte, error) {
	type alias %[1]s
	return json.Marshal(struct {
		D string `+"`json:%[2]q`"+`
		alias
	}{%[3]q, alias(v)})
}

func (v *%[1]s) UnmarshalJSON(b []byte) error {
	type alias %[1]s
	w := struct {
		D string `+"`json:%[2]q`"+`
		*alias
	}{alias: (*alias)(v)}
	if err := json.Unmarshal(b, &w); err != nil {
		return err
	}
	if w.D != %[3]q {
		return fmt.Errorf("api: %[1]s: %[2]s is %%q, want %%q", w.D, %[3]q)
	}
	return nil
}

`, q.name, q.disc, q.discVal)
}

// ---- responses, methods, events ------------------------------------------

func (g *gen) emitResponses(sr *Schema) {
	rr := sr.Defs["ResponseResult"]
	g.done["ResponseResult"] = true
	for _, v := range rr.OneOf {
		val := *v.Properties["type"].Const
		name := pascal(val) + "Response"
		g.kinds[name] = kStruct
		g.queue = append(g.queue, pending{name: name, s: v, unionName: "Response", disc: "type", discVal: val})
	}
	g.claim("ResponseVariant", "responses")
	g.p("// ResponseVariant is implemented by every typed method response.\ntype ResponseVariant interface{ isResponse() }\n\n")
	g.drain()
}

func (g *gen) emitMethods(req *Schema) {
	var methods []string
	params := map[string]string{}
	for _, v := range req.OneOf {
		m := *v.Properties["method"].Const
		methods = append(methods, m)
		params[m] = refName(v.Properties["params"].Ref)
	}
	sort.Strings(methods)
	methodNames := map[string]bool{}
	for _, m := range methods {
		if streaming[m] {
			continue
		}
		resp, ok := responses[m]
		if !ok {
			fail("no response mapping for method %s (add it to responses.go)", m)
		}
		rt := pascal(resp) + "Response"
		if _, ok := g.kinds[rt]; !ok {
			fail("method %s maps to unknown response %s", m, resp)
		}
		fn := pascal(m)
		if methodNames[fn] {
			fail("method name %s generated twice", fn)
		}
		methodNames[fn] = true
		note := ""
		if !verified[m] {
			note = " The response type was not verified against a live server."
		}
		pt := params[m]
		if ps := g.defs[pt]; ps != nil && len(ps.Properties) == 0 {
			pt = "EmptyParams" // no fields: drop the argument
		}
		if pt == "EmptyParams" {
			g.p("// %s calls %q.%s\nfunc (c Client) %s(ctx context.Context) (%s, error) {\nvar r %s\nerr := c.Caller.Call(ctx, %q, EmptyParams{}, &r)\nreturn r, err\n}\n\n", fn, m, note, fn, rt, rt, m)
			continue
		}
		g.p("// %s calls %q.%s\nfunc (c Client) %s(ctx context.Context, p %s) (%s, error) {\nvar r %s\nerr := c.Caller.Call(ctx, %q, p, &r)\nreturn r, err\n}\n\n", fn, m, note, fn, pt, rt, rt, m)
	}
	// Method name list for introspection and tests.
	g.p("// Methods lists every request method in the schema.\nvar Methods = []string{\n")
	for _, m := range methods {
		g.p("%q,\n", m)
	}
	g.p("}\n\n")
}

func (g *gen) emitEnvelope(ev, sub *Schema) {
	// Subscription-event kinds map 1:1, in order, onto the SubscriptionEventData refs.
	kinds := sub.Defs["SubscriptionEventKind"].Enum
	data := sub.Defs["SubscriptionEventData"].AnyOf
	if len(kinds) != len(data) {
		fail("subscription event kinds (%d) and data (%d) differ", len(kinds), len(data))
	}
	g.p("// subscriptionEventTypes maps subscription-only event kinds to their payload.\nfunc decodeSubscriptionEvent(kind string, b []byte) (any, bool, error) {\nswitch kind {\n")
	for i, k := range kinds {
		g.p("case %q:\nvar v %s\nerr := json.Unmarshal(b, &v)\nreturn v, true, err\n", k, refName(data[i].Ref))
	}
	g.p("}\nreturn nil, false, nil\n}\n\n")
	g.p("// DecodeSubscriptionEvent decodes the data of a subscription-only event\n// (see SubscriptionEventKind). ok is false for other kinds.\nfunc DecodeSubscriptionEvent(kind string, data []byte) (v any, ok bool, err error) {\nreturn decodeSubscriptionEvent(kind, data)\n}\n\n")
}

// variantNames overrides how inline union variants are named.
// Format args: union name, pascal(discriminator value).
var variantNames = map[string]string{
	"EventData": "Event%[2]s", // EventPaneCreated, EventTabMoved, ...
}

// ---- helpers --------------------------------------------------------------

func (g *gen) doc(name, desc string) {
	if desc == "" {
		return
	}
	lines := wrap(name+": "+desc, 76)
	for _, l := range lines {
		g.p("// %s\n", l)
	}
}

var initialisms = map[string]string{
	"id": "ID", "ids": "IDs", "url": "URL", "ttl": "TTL", "pid": "PID", "tty": "TTY", "ssh": "SSH",
	"api": "API", "json": "JSON", "ui": "UI", "uri": "URI", "http": "HTTP", "ansi": "ANSI", "os": "OS",
}

func pascal(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool {
		return !(unicode.IsLetter(r) || unicode.IsDigit(r))
	})
	var b strings.Builder
	for _, p := range parts {
		if up, ok := initialisms[strings.ToLower(p)]; ok {
			b.WriteString(up)
			continue
		}
		r := []rune(p)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	out := b.String()
	if out == "" || unicode.IsDigit([]rune(out)[0]) {
		out = "V" + out
	}
	return out
}

func wrap(s string, width int) []string {
	var lines []string
	var cur strings.Builder
	for _, w := range strings.Fields(s) {
		if cur.Len() > 0 && cur.Len()+1+len(w) > width {
			lines = append(lines, cur.String())
			cur.Reset()
		}
		if cur.Len() > 0 {
			cur.WriteByte(' ')
		}
		cur.WriteString(w)
	}
	if cur.Len() > 0 {
		lines = append(lines, cur.String())
	}
	return lines
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func check(err error) {
	if err != nil {
		fail("%v", err)
	}
}

func fail(f string, a ...any) {
	fmt.Fprintf(os.Stderr, "herdr-gen: "+f+"\n", a...)
	os.Exit(1)
}
